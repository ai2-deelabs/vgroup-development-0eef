/* ============================================================
   SCROLL REVEAL
   ============================================================ */
function revealAll(){
  document.querySelectorAll("[data-reveal]").forEach(function(el){ el.classList.add("in"); });
}
if(typeof IntersectionObserver === "undefined"){
  revealAll();                                  /* no observer support: just show everything */
}else{
  var delivered = 0;
  var io = new IntersectionObserver(function(es){
    delivered += es.length;
    es.forEach(function(e){ if(e.isIntersecting){ e.target.classList.add("in"); io.unobserve(e.target); } });
  }, {threshold:.1, rootMargin:"0px 0px -7% 0px"});
  document.querySelectorAll("[data-reveal]").forEach(function(el){ io.observe(el); });
  /* Failsafe: a working observer always delivers an initial entry per target.
     If nothing is ever delivered the content would stay invisible, so show it.
     Content must never be gated on an animation firing. */
  setTimeout(function(){ if(delivered === 0) revealAll(); }, 1500);
}

/* ============================================================
   MAGNETIC HOVER on CTAs (pointer-fine only)
   ============================================================ */
if(matchMedia("(hover:hover) and (pointer:fine)").matches &&
   !matchMedia("(prefers-reduced-motion:reduce)").matches){
  document.querySelectorAll("[data-magnet]").forEach(function(el){
    el.addEventListener("pointermove", function(e){
      var r = el.getBoundingClientRect();
      var dx = (e.clientX - (r.left + r.width/2)) / (r.width/2);
      var dy = (e.clientY - (r.top + r.height/2)) / (r.height/2);
      el.style.transform = "translate(" + (dx*5).toFixed(2) + "px," + (dy*4).toFixed(2) + "px)";
    });
    el.addEventListener("pointerleave", function(){ el.style.transform = ""; });
  });
}


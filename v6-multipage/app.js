/* ============================================================
   FORM — design demo, no backend
   ============================================================ */
(function(){
  var form = document.getElementById("cform"),
      note = document.getElementById("fnote"),
      name = document.getElementById("f-name"),
      mail = document.getElementById("f-mail"),
      MAIL = /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/;
  if(!form || !note || !name || !mail) return;   /* this page has no form */

  function mark(el, bad){
    el.setAttribute("aria-invalid", bad ? "true" : "false");
    el.style.borderColor = bad ? "var(--err)" : "";
  }
  [name, mail].forEach(function(el){
    el.addEventListener("input", function(){ mark(el, false); });
  });

  form.addEventListener("submit", function(e){
    e.preventDefault();               /* no backend yet - validate, then report */
    var nameBad = name.value.trim() === "",
        mailBad = !MAIL.test(mail.value.trim());
    mark(name, nameBad);
    mark(mail, mailBad);
    if(nameBad || mailBad){
      note.textContent = nameBad ? I18N[LANG].errName : I18N[LANG].errMail;
      note.style.color = "var(--err)";
      (nameBad ? name : mail).focus();
      return;
    }
    note.textContent = I18N[LANG].formNote;
    note.style.color = "var(--forest)";
  });
})();

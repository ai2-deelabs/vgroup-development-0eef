var LANG_KEY = "vgroup-lang";
var LANG = (function(){ try { return localStorage.getItem(LANG_KEY) || "th"; }
                        catch(e){ return "th"; } })();   /* persists across pages */

function setLang(l){
  if(!I18N[l]) return;
  LANG = l;
  try { localStorage.setItem(LANG_KEY, l); } catch(e){}
  document.documentElement.lang = l;
  var d = I18N[l];

  document.querySelectorAll("[data-i18n]").forEach(function(el){
    var v = d[el.getAttribute("data-i18n")];
    if(v == null) return;
    if(/[<&]/.test(v)) el.innerHTML = v; else el.textContent = v;
  });
  document.querySelectorAll("[data-i18n-attr]").forEach(function(el){
    var v = d[el.getAttribute("data-i18n-ph")];
    if(v != null) el.setAttribute(el.getAttribute("data-i18n-attr"), v);
  });
  document.querySelectorAll(".lang button").forEach(function(b){
    b.setAttribute("aria-pressed", String(b.dataset.lang === l));
  });
}

document.querySelectorAll(".lang button").forEach(function(b){
  b.addEventListener("click", function(){ setLang(b.dataset.lang); });
});
if(LANG !== "th") setLang(LANG);   /* restore the choice made on a previous page */

